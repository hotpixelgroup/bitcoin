// Exercise the learner journey, persisted first attempts and bounded toy models.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = (process.env.VIBES_QA_URL || 'http://127.0.0.1:21880').replace(/\/$/, '');
(async () => {
  const browser = await chromium.launch({headless: true, ...(process.env.VIBES_BROWSER_CHANNEL ? {channel: process.env.VIBES_BROWSER_CHANNEL} : {})});
  const page = await browser.newPage({viewport: {width: 1280, height: 900}, reducedMotion: 'reduce'});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(base + '/demo.html');
    await page.locator('#connection').filter({hasText: 'Demo'}).waitFor();
    assert.equal(await page.locator('#composer').isVisible(), false);
    assert.match(await page.locator('#journey-progress').innerText(), /0 of 5 foundations/);
    await page.locator('#start-learning').click();
    assert.match(await page.locator('#predict-title').innerText(), /coins in your wallet/);
    await page.keyboard.press('Escape');
    await page.locator('[data-curated="utxos"]').click();
    await page.locator('#prediction-change').check();
    await page.locator('#predict-reflection summary').click();
    await page.locator('#predict-confidence').selectOption('medium');
    await page.locator('#predict-reason').fill('I expect change because inputs are consumed whole.');
    await page.locator('#predict-run').click();
    await page.locator('#lesson').waitFor();
    assert.match(await page.locator('#lesson-takeaway').innerText(), /Inputs are spent whole/);
    assert.equal(await page.locator('#full-observations').getAttribute('open'), null);
    assert.match(await page.locator('.evidence-frame').innerText(), /100 BTC/);
    await page.getByRole('button', {name: 'Next observation', exact: true}).click();
    assert.match(await page.locator('.evidence-frame').innerText(), /Change:/);
    await page.getByRole('button', {name: 'Next observation', exact: true}).click();
    assert.equal(await page.getByRole('button', {name: 'Next observation', exact: true}).isDisabled(), true);
    await page.locator('#lesson-terms summary').click();
    await page.waitForTimeout(1700); // a status poll must not collapse an open glossary
    assert.notEqual(await page.locator('#lesson-terms details').getAttribute('open'), null);
    await page.locator('#reflection summary').click();
    assert.match(await page.locator('#reflection').innerText(), /inputs are consumed whole/);
    await page.locator('#reflection-note').fill('The fee is the input/output difference.');
    await page.locator('#reflection-confidence').selectOption('high');
    await page.getByRole('button', {name: 'Save reflection', exact: true}).click();
    await page.getByText('Your first reflection is saved.', {exact: true}).waitFor();
    await page.getByRole('button', {name: 'Practice this idea with a different question'}).click();
    await page.locator('#practice-question input[value="0"]').check();
    await page.getByRole('button', {name: 'Save practice answer'}).click();
    await page.locator('#practice-question [role="status"]').filter({hasText: '11,400'}).waitFor();
    assert.equal(await page.locator('#practice-question input:checked').isDisabled(), true);
    await page.reload();
    await page.locator('#lesson').waitFor();
    await page.locator('#reflection summary').click();
    assert.equal(await page.locator('#reflection-note').inputValue(), 'The fee is the input/output difference.');
    assert.equal(await page.locator('#reflection-note').isDisabled(), true);
    assert.match(await page.locator('#practice-queue').innerText(), /needs another look/);
    await page.getByRole('button', {name: 'Practice: Where does the change in a payment come from?', exact: true}).click();
    assert.match(await page.locator('#practice-question legend').innerText(), /40,000/);

    await page.locator('#model-work summary').click();
    await page.getByRole('button', {name: 'Try 100 hashes'}).click();
    await page.locator('#model-work [role="status"]').filter({hasText: '100 attempts'}).waitFor();
    assert.match(await page.locator('.toy-hash').innerText(), /^[a-f0-9]{64}$/);
    await page.locator('#work-target').selectOption('2');
    assert.match(await page.locator('#model-work [role="status"]').innerText(), /No attempts yet/);
    await page.locator('#model-privacy summary').click();
    assert.equal(await page.locator('.flow-row').filter({hasText: 'destination 1'}).count(), 3);
    await page.locator('#fresh-addresses').check();
    assert.equal(await page.locator('.flow-row').filter({hasText: 'destination 1'}).count(), 1);
    assert.match(await page.locator('#model-privacy [role="status"]').innerText(), /do not guarantee anonymity/);
    await page.locator('#model-lightning summary').click();
    await page.getByRole('button', {name: 'Bob pays Alice', exact: true}).click();
    assert.match(await page.locator('#model-lightning').innerText(), /Choose a whole number from 1 to 20,000/);
    await page.getByRole('button', {name: 'Alice pays Bob', exact: true}).click();
    assert.match(await page.locator('#model-lightning .takeaway').innerText(), /Alice: 50,000 sat · Bob: 50,000 sat/);
    await page.getByRole('button', {name: 'Settle and close model channel'}).click();
    assert.equal(await page.getByRole('button', {name: 'Alice pays Bob', exact: true}).isDisabled(), true);
    await page.getByRole('button', {name: 'Reset model', exact: true}).click();
    assert.match(await page.locator('#model-lightning .takeaway').innerText(), /Alice: 80,000/);
    await page.locator('#channel-amount').fill('80000');
    await page.getByRole('button', {name: 'Alice pays Bob', exact: true}).click();
    await page.locator('#channel-amount').fill('1');
    await page.getByRole('button', {name: 'Alice pays Bob', exact: true}).click();
    assert.match(await page.locator('#model-lightning').innerText(), /no outgoing balance/);
    assert.match(await page.locator('#model-lightning .takeaway').innerText(), /Alice: 0 sat · Bob: 100,000 sat/);
    await page.getByRole('button', {name: 'Reset model', exact: true}).click();
    const downloaded = page.waitForEvent('download');
    await page.locator('#study-export').click();
    const record = JSON.parse(fs.readFileSync(await (await downloaded).path(), 'utf8'));
    assert.equal(record.study.entries.filter(row => row.stage === 'practice').length, 1);
    assert.equal(record.study.entries.find(row => row.stage === 'practice').correct, false);
    assert.equal(record.prediction_context[0].confidence, 'medium');
    await page.addScriptTag({path: process.env.AXE_MODULE || require.resolve('axe-core/axe.min.js')});
    for (const width of [1280, 900, 761, 760, 390, 320, 195]) {
      await page.setViewportSize({width, height: 900});
      await page.waitForFunction(() => parseFloat(getComputedStyle(document.documentElement).scrollPaddingTop) > document.querySelector('.topbar').getBoundingClientRect().height);
      await page.locator('a[href="#current"]:visible').click();
      assert.equal(await page.evaluate(() => document.querySelector('#current h2').getBoundingClientRect().top >= document.querySelector('.topbar').getBoundingClientRect().bottom), true, `section heading behind sticky header at ${width}px`);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `learning page overflow at ${width}px`);
      const audit = await page.evaluate(() => axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']}}));
      assert.deepEqual(audit.violations.map(row => ({id: row.id, targets: row.nodes.map(node => node.target)})), [], `learning accessibility at ${width}px`);
    }
    assert.deepEqual(errors, []);
    console.log('learning journey passed: evidence, reflections, first attempts, models, export and accessibility');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
